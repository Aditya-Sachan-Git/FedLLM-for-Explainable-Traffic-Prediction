@dataclass
class HorizonMetrics:
    """MAE and RMSE for a single forecast horizon (flow and speed separately)."""
    horizon_label: str
    mae_flow:  float = 0.0
    rmse_flow: float = 0.0
    mae_speed: float = 0.0
    rmse_speed:float = 0.0
    n_valid:   int   = 0


class MetricCalculator:
    """
    Accumulates absolute errors and squared errors across the test set,
    then computes MAE and RMSE for each horizon.

    Handles NaN gracefully: samples where the parser failed to extract a
    value are excluded from the metric denominators (reported as n_valid).
    """

    HORIZONS = [
        ("15-min (t+3)",  "f15", "s15"),
        ("30-min (t+6)",  "f30", "s30"),
        ("45-min (t+9)",  "f45", "s45"),
        ("60-min (t+12)", "f60", "s60"),
    ]

    def __init__(self):
        # flow abs errors, flow squared errors, speed ..., count
        self._errors: Dict[str, Dict[str, List[float]]] = {
            lbl: {"flow_abs": [], "flow_sq": [], "speed_abs": [], "speed_sq": []}
            for lbl, _, _ in self.HORIZONS
        }

    def accumulate(self, gt: ParsedForecast, pred: ParsedForecast) -> None:
        """Add one sample's errors."""
        for lbl, f_attr, s_attr in self.HORIZONS:
            gt_f  = getattr(gt,   f_attr)
            pr_f  = getattr(pred, f_attr)
            gt_s  = getattr(gt,   s_attr)
            pr_s  = getattr(pred, s_attr)

            if gt_f is not None and pr_f is not None:
                err = abs(gt_f - pr_f)
                self._errors[lbl]["flow_abs"].append(err)
                self._errors[lbl]["flow_sq"].append(err ** 2)

            if gt_s is not None and pr_s is not None:
                err = abs(gt_s - pr_s)
                self._errors[lbl]["speed_abs"].append(err)
                self._errors[lbl]["speed_sq"].append(err ** 2)

    def compute(self) -> List[HorizonMetrics]:
        """Compute and return MAE/RMSE for each horizon."""
        results = []
        for lbl, _, _ in self.HORIZONS:
            e = self._errors[lbl]
            n = len(e["flow_abs"])

            mae_f  = float(np.mean(e["flow_abs"]))  if n else float("nan")
            rmse_f = float(math.sqrt(np.mean(e["flow_sq"])))  if n else float("nan")

            ns = len(e["speed_abs"])
            mae_s  = float(np.mean(e["speed_abs"])) if ns else float("nan")
            rmse_s = float(math.sqrt(np.mean(e["speed_sq"]))) if ns else float("nan")

            results.append(HorizonMetrics(
                horizon_label=lbl,
                mae_flow=mae_f, rmse_flow=rmse_f,
                mae_speed=mae_s, rmse_speed=rmse_s,
                n_valid=n,
            ))
        return results


