"""
FedLLM: Privacy-Preserving Explainable Traffic Flow Prediction Pipeline
Phase 6: Inference & Evaluation Dashboard
=============================================================================
This module loads the globally aggregated FedCSS LoRA adapter, runs blind
inference on held-out test prompts, parses multi-horizon numerical forecasts
from the generated text, computes MAE / RMSE metrics, and renders a rich
console dashboard for project demonstration.

Pipeline:
  1. Model Loading  — Quantised base LLM + FedCSS LoRA adapter injection.
  2. Blind Testing  — Only the [input] block is shown to the model; the
                      ground-truth [output] is hidden until comparison.
  3. Output Parsing — Robust regex extracts flow & speed per horizon from
                      free-form LLM text.
  4. Metric Calculation — MAE and RMSE for flow and speed at each horizon.
  5. Demo Display   — Console dashboard with colour-coded panels for the
                      first N samples.
"""

