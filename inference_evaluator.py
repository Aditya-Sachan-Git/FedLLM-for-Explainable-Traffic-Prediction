# 2. Model Loader (Base LLM + FedCSS LoRA Adapter)
# =============================================================================

class FedLLMInferenceModel:
    """
    Loads the quantised base LLM and injects the global FedCSS LoRA adapter.

    Generation is configured for deterministic, structured output:
      - temperature = 0.05 (near-greedy; avoids hallucinated numbers)
      - repetition_penalty = 1.1 (suppresses repetitive filler text)
      - max_new_tokens = 512 (enough for forecast block + rationale)
      - do_sample = False (greedy decoding is most reproducible)
    """

    PROMPT_TEMPLATE = (
        "<|im_start|>system\n{instruction}<|im_end|>\n"
        "<|im_start|>user\n{input}<|im_end|>\n"
        "<|im_start|>assistant\n"
    )

    def __init__(
        self,
        model_name_or_path: str,
        adapter_checkpoint_dir: str,
        use_4bit: bool = True,
        max_new_tokens: int = 512,
        temperature: float = 0.05,
        device: str = "auto",
    ):
        self.model_name_or_path = model_name_or_path
        self.adapter_checkpoint_dir = adapter_checkpoint_dir
        self.use_4bit = use_4bit
        self.max_new_tokens = max_new_tokens
        self.temperature = temperature
        self.device = device

        self._model = None
        self._tokenizer = None
        self._loaded = False

    def load(self) -> bool:
        """
        Loads the base model with 4-bit quantization and injects the LoRA adapter.
        Returns True if successful, False if running in simulation mode.
        """
        if not (HAS_TORCH and HAS_HF):
            logger.warning(
                "PyTorch / transformers / peft not fully installed. "
                "Running in SIMULATION mode — will use ground-truth output as mock generation."
            )
            self._loaded = False
            return False

        logger.info(f"Loading tokenizer: {self.model_name_or_path}")
        tokenizer = AutoTokenizer.from_pretrained(
            self.model_name_or_path,
            trust_remote_code=True,
            padding_side="left",    # Left-pad for batch generation
        )
        if tokenizer.pad_token is None:
            tokenizer.pad_token = tokenizer.eos_token

        # ── 4-bit NF4 quantization ─────────────────────────────────────────────
        bnb_config = None
        if self.use_4bit and torch.cuda.is_available():
            compute_dtype = (
                torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
            )
            bnb_config = BitsAndBytesConfig(
                load_in_4bit=True,
                bnb_4bit_quant_type="nf4",
                bnb_4bit_use_double_quant=True,
                bnb_4bit_compute_dtype=compute_dtype,
            )
            logger.info("4-bit NF4 QLoRA quantization enabled.")

        torch_dtype = torch.bfloat16 if torch.cuda.is_available() else torch.float32
        device_map = self.device if self.device != "auto" else "auto"

        logger.info(f"Loading base model: {self.model_name_or_path} ...")
        base_model = AutoModelForCausalLM.from_pretrained(
            self.model_name_or_path,
            quantization_config=bnb_config,
            device_map=device_map,
            torch_dtype=torch_dtype,
            trust_remote_code=True,
        )

        # ── Inject FedCSS LoRA adapter ─────────────────────────────────────────
        # The adapter directory must contain adapter_config.json and adapter weights.
        # If no PEFT-formatted adapter exists, fall back to base model only.
        if os.path.isdir(self.adapter_checkpoint_dir) and \
           os.path.exists(os.path.join(self.adapter_checkpoint_dir, "adapter_config.json")):
            logger.info(f"Injecting LoRA adapter from: {self.adapter_checkpoint_dir}")
            model = PeftModel.from_pretrained(
                base_model,
                self.adapter_checkpoint_dir,
                is_trainable=False,
            )
            logger.info("LoRA adapter injected successfully. Merging for fast inference ...")
            # Merge adapter weights into base model for maximum inference speed
            model = model.merge_and_unload()
        else:
            logger.warning(
                f"No PEFT adapter_config.json found at '{self.adapter_checkpoint_dir}'. "
                "Proceeding with base model only (zero-shot evaluation)."
            )
            model = base_model

        model.eval()
        self._model = model
        self._tokenizer = tokenizer
        self._loaded = True
        logger.info("Model ready for inference.")
        return True

    def generate(self, instruction: str, user_input: str) -> str:
        """
        Runs inference for a single prompt. Returns the raw generated string.
        In simulation mode (no GPU/LLM), returns an empty string.
        """
        if not self._loaded or self._model is None:
            return ""

        prompt = self.PROMPT_TEMPLATE.format(
            instruction=instruction,
            input=user_input,
        )
        input_ids = self._tokenizer(
            prompt,
            return_tensors="pt",
            truncation=True,
            max_length=1024,
        ).input_ids

        if torch.cuda.is_available():
            input_ids = input_ids.to(self._model.device)

        with torch.no_grad():
            output_ids = self._model.generate(
                input_ids,
                max_new_tokens=self.max_new_tokens,
                # ── Deterministic / structured output settings ────────────────
                do_sample=False,            # Greedy decoding — most reproducible
                temperature=None,           # Must be None when do_sample=False
                top_p=None,
                repetition_penalty=1.1,     # Suppress repetitive filler text
                eos_token_id=self._tokenizer.eos_token_id,
                pad_token_id=self._tokenizer.pad_token_id,
            )

        # Strip the input tokens and decode only the generated portion
        generated_ids = output_ids[0][input_ids.shape[-1]:]
        return self._tokenizer.decode(generated_ids, skip_special_tokens=True)


