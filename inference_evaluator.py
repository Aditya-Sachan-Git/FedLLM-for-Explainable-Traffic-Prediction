def _c(text: str, colour: str) -> str:
    """Wrap text in an ANSI colour escape only when stdout supports it."""
    if sys.stdout.isatty() or os.environ.get("FORCE_COLOR"):
        return f"{colour}{text}{RESET}"
    return text

def _box(title: str, body: str, width: int = 78, colour: str = CYAN) -> str:
    """Renders a simple box-bordered panel."""
    border = "─" * (width - 2)
    top    = f"┌{border}┐"
    sep    = f"├{border}┤"
    bot    = f"└{border}┘"
    title_line = f"│ {_c(title, colour + BOLD):<{width + len(colour + BOLD + RESET) - 2}} │"
    lines = [top, title_line, sep]
    for raw_line in body.splitlines():
        # Word-wrap each line to fit inside the box
        for segment in (textwrap.wrap(raw_line, width - 4) or [""]):
            pad = width - 4 - len(segment)
            lines.append(f"│  {segment}{' ' * pad}  │")
    lines.append(bot)
    return "\n".join(lines)


