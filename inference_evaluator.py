# 4. Console Dashboard Renderer
# =============================================================================

class DashboardRenderer:
    """Renders beautiful console panels for the demo samples."""

    WIDTH = 82

    @staticmethod
    def _divider(char: str = "═", width: int = 82, colour: str = CYAN) -> str:
        return _c(char * width, colour)

    @classmethod
    def render_sample(
        cls,
        sample_idx: int,
        record: Dict[str, Any],
        gt: ParsedForecast,
        pred: ParsedForecast,
        generated_text: str,
        simulation_mode: bool = False,
    ) -> None:
        W = cls.WIDTH
        sep = cls._divider("─", W, BLUE)

        print()
        print(cls._divider("═", W, CYAN))
        header = f"  SAMPLE {sample_idx + 1}"
        if simulation_mode:
            header += "  [SIMULATION MODE — Ground-Truth used as mock prediction]"
        print(_c(header, CYAN + BOLD))
        print(cls._divider("═", W, CYAN))

        # ── [1] GIVEN CONTEXT ──────────────────────────────────────────────────
        print(_c("\n[1] GIVEN CONTEXT (Input fed to FedLLM)", BOLD + YELLOW))
        print(sep)
        context_lines = record["input"].strip().splitlines()
        for line in context_lines[:28]:           # cap to avoid console flood
            print(f"  {line}")
        if len(context_lines) > 28:
            print(f"  ... [{len(context_lines) - 28} more lines hidden] ...")
        print()

        # ── [2] ACTUAL vs. PREDICTED ───────────────────────────────────────────
        print(_c("\n[2] ACTUAL vs. PREDICTED (Multi-Horizon Forecast)", BOLD + GREEN))
        print(sep)

        horizons = [
            ("15-min (t+3)",  gt.f15, pred.f15, gt.s15, pred.s15),
            ("30-min (t+6)",  gt.f30, pred.f30, gt.s30, pred.s30),
            ("45-min (t+9)",  gt.f45, pred.f45, gt.s45, pred.s45),
            ("60-min (t+12)", gt.f60, pred.f60, gt.s60, pred.s60),
        ]

        header_row = (
            f"  {'Horizon':<16} "
            f"{'Flow-GT':>10} {'Flow-Pred':>10} {'ΔFlow':>8} | "
            f"{'Speed-GT':>10} {'Speed-Pred':>10} {'ΔSpeed':>8}"
        )
        print(_c(header_row, BOLD))
        print(f"  {'─'*16} {'─'*10} {'─'*10} {'─'*8}   {'─'*10} {'─'*10} {'─'*8}")

        for (lbl, gf, pf, gs, ps) in horizons:
            if gf is not None and pf is not None:
                df = pf - gf
                ds = (ps - gs) if (gs is not None and ps is not None) else None
                colour_f = GREEN if abs(df) < 20 else (YELLOW if abs(df) < 50 else RED)
                colour_s = GREEN if (ds is not None and abs(ds) < 3) else (YELLOW if (ds is not None and abs(ds) < 8) else RED)

                flow_str  = f"{gf:>10.1f} {_c(f'{pf:>10.1f}', colour_f)} {_c(f'{df:>+8.1f}', colour_f)}"
                speed_str = (
                    f"{gs:>10.1f} {_c(f'{ps:>10.1f}', colour_s)} {_c(f'{ds:>+8.1f}', colour_s)}"
                    if (gs is not None and ps is not None and ds is not None)
                    else f"{'N/A':>10} {'N/A':>10} {'N/A':>8}"
                )
                print(f"  {lbl:<16} {flow_str} | {speed_str}")
            else:
                print(f"  {lbl:<16} {'PARSE FAIL':>31} | {'PARSE FAIL':>31}")
        print()

        # ── [3] LLM RATIONALE ──────────────────────────────────────────────────
        print(_c("\n[3] FedLLM Generated Physical Rationale", BOLD + MAGENTA))
        print(sep)
        rationale = pred.rationale or generated_text[:600]
        for line in rationale.splitlines():
            wrapped = textwrap.wrap(line, W - 4) or [""]
            for w in wrapped:
                print(f"  {w}")
        print()

    @classmethod
    def render_metrics_table(cls, metrics: List[HorizonMetrics]) -> None:
        """Renders the final MAE / RMSE table."""
        W = cls.WIDTH
        print()
        print(cls._divider("═", W, GREEN))
        print(_c("  FINAL EVALUATION METRICS", BOLD + GREEN))
        print(cls._divider("═", W, GREEN))
        print(
            _c(
                f"  {'Horizon':<16} "
                f"{'MAE-Flow':>12} {'RMSE-Flow':>12} "
                f"{'MAE-Speed':>12} {'RMSE-Speed':>12}  {'N':>6}",
                BOLD,
            )
        )
        print(f"  {'─'*16} {'─'*12} {'─'*12} {'─'*12} {'─'*12}  {'─'*6}")

        for m in metrics:
            def _fmt(v: float) -> str:
                return f"{v:12.4f}" if not math.isnan(v) else f"{'N/A':>12}"
            colour = GREEN if (not math.isnan(m.mae_flow) and m.mae_flow < 30) else YELLOW
            row = (
                f"  {m.horizon_label:<16} "
                f"{_c(_fmt(m.mae_flow), colour)} {_c(_fmt(m.rmse_flow), colour)} "
                f"{_c(_fmt(m.mae_speed), colour)} {_c(_fmt(m.rmse_speed), colour)}"
                f"  {m.n_valid:>6}"
            )
            print(row)

        print(cls._divider("═", W, GREEN))


