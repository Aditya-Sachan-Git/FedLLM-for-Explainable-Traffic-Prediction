@dataclass
class ParsedForecast:
    """Holds the numerically parsed multi-horizon predictions from LLM output."""
    f15: Optional[float] = None   # Flow  @ t+3  (15 min)
    s15: Optional[float] = None   # Speed @ t+3
    f30: Optional[float] = None   # Flow  @ t+6  (30 min)
    s30: Optional[float] = None   # Speed @ t+6
    f45: Optional[float] = None   # Flow  @ t+9  (45 min)
    s45: Optional[float] = None   # Speed @ t+9
    f60: Optional[float] = None   # Flow  @ t+12 (60 min)
    s60: Optional[float] = None   # Speed @ t+12
    rationale: str = ""
    parse_success: bool = False


class ForecastParser:
    """
    Extracts multi-horizon Flow and Speed values from free-form LLM text.

    The target format (as generated by prompt_engineer.py) is:
        ### Multi-Horizon Traffic Forecast:
        - 15-min Ahead (t+3): Flow = 126.2 veh/5min | Speed = 56.7 mph
        - 30-min Ahead (t+6): Flow = 77.4 veh/5min | Speed = 60.0 mph
        - 45-min Ahead (t+9): Flow = 109.1 veh/5min | Speed = 58.5 mph
        - 60-min Ahead (t+12): Flow = 115.4 veh/5min | Speed = 57.8 mph

    Multiple regex patterns are tried in order from most to least specific
    to handle minor LLM formatting variations.
    """

    # ── Primary patterns: match the canonical format ───────────────────────────
    # Captures: horizon label (t+3 / t+6 / t+9 / t+12), flow, speed
    _CANONICAL = re.compile(
        r"(\d+)-min\s+Ahead\s+\(t\+(\d+)\)\s*:?\s*"
        r"Flow\s*=\s*([\d]+\.?[\d]*)\s*veh/5min\s*\|?\s*"
        r"Speed\s*=\s*([\d]+\.?[\d]*)\s*mph",
        re.IGNORECASE,
    )

    # ── Fallback 1: plain "t+N: Flow X | Speed Y" form (no "min Ahead") ───────
    _TPLUS = re.compile(
        r"t\+(\d+)\s*[:\-]\s*"
        r"Flow\s*=?\s*([\d]+\.?[\d]*)\s*(?:veh/5min)?\s*[|\-,]?\s*"
        r"Speed\s*=?\s*([\d]+\.?[\d]*)\s*(?:mph)?",
        re.IGNORECASE,
    )

    # ── Fallback 2: bare numbers in a table or CSV row ────────────────────────
    # e.g.  "t+3  | 126.2  | 56.7"
    _TABLE_ROW = re.compile(
        r"t\+(\d+)\s*[|,]\s*([\d]+\.?[\d]*)\s*[|,]\s*([\d]+\.?[\d]*)",
        re.IGNORECASE,
    )

    # ── Rationale block ────────────────────────────────────────────────────────
    _RATIONALE = re.compile(
        r"###\s*Spatial-Temporal Rationale.*?:\s*\n(.*)",
        re.IGNORECASE | re.DOTALL,
    )

    # Mapping from t+ index → attribute names
    _HORIZON_MAP = {
        "3":  ("f15", "s15"),
        "6":  ("f30", "s30"),
        "9":  ("f45", "s45"),
        "12": ("f60", "s60"),
    }

    @classmethod
    def parse(cls, generated_text: str) -> ParsedForecast:
        """Parse a single LLM output string into a ParsedForecast dataclass."""
        result = ParsedForecast()

        # Try patterns from most to least specific
        for pattern, groups in [
            (cls._CANONICAL, "canonical"),
            (cls._TPLUS,     "tplus"),
            (cls._TABLE_ROW, "table"),
        ]:
            for m in pattern.finditer(generated_text):
                if groups == "canonical":
                    # groups: (min_label, t_idx, flow, speed)
                    t_idx = m.group(2)
                    flow  = float(m.group(3))
                    speed = float(m.group(4))
                else:
                    # groups: (t_idx, flow, speed)
                    t_idx = m.group(1)
                    flow  = float(m.group(2))
                    speed = float(m.group(3))

                if t_idx in cls._HORIZON_MAP:
                    f_attr, s_attr = cls._HORIZON_MAP[t_idx]
                    # Only set once (first match wins)
                    if getattr(result, f_attr) is None:
                        setattr(result, f_attr, flow)
                    if getattr(result, s_attr) is None:
                        setattr(result, s_attr, speed)

        # Extract rationale text
        rat_m = cls._RATIONALE.search(generated_text)
        if rat_m:
            result.rationale = rat_m.group(1).strip()
        else:
            # Fall back: everything after the forecast block
            split = generated_text.split("Rationale")
            result.rationale = split[-1].strip() if len(split) > 1 else ""

        # Mark success if we parsed at least the two most-important horizons
        result.parse_success = (
            result.f15 is not None and result.f60 is not None
        )
        return result

    @classmethod
    def parse_ground_truth(cls, output_text: str) -> ParsedForecast:
        """Extracts ground-truth values from the JSONL 'output' field."""
        return cls.parse(output_text)


