# 5. Main Evaluation Loop
# =============================================================================

def run_evaluation(
    test_jsonl: str,
    model_name_or_path: str,
    adapter_dir: str,
    use_4bit: bool = True,
    max_new_tokens: int = 512,
    temperature: float = 0.05,
    max_samples: int = 200,
    demo_samples: int = 3,
    results_output: str = "./eval_results.json",
) -> Dict[str, Any]:
    """
    Full evaluation pipeline.

    Parameters
    ----------
    test_jsonl         : Path to test_prompts.jsonl
    model_name_or_path : Base LLM HF model ID or local path
    adapter_dir        : Directory containing the FedCSS final LoRA adapter
    use_4bit           : Enable 4-bit NF4 QLoRA quantization
    max_new_tokens     : Max tokens to generate per sample
    temperature        : Generation temperature (low = more deterministic)
    max_samples        : Maximum number of test samples to evaluate
    demo_samples       : Number of samples to display in the console dashboard
    results_output     : Path to save the JSON evaluation report

    Returns
    -------
    Dictionary with metric results and per-sample records.
    """
    if not os.path.exists(test_jsonl):
        raise FileNotFoundError(f"Test JSONL not found: {test_jsonl}")

    # ── Load test records ──────────────────────────────────────────────────────
    records: List[Dict[str, Any]] = []
    with open(test_jsonl, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                try:
                    records.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    records = records[:max_samples]
    logger.info(f"Loaded {len(records)} test records from {test_jsonl}")

    # ── Load model ────────────────────────────────────────────────────────────
    inference_model = FedLLMInferenceModel(
        model_name_or_path=model_name_or_path,
        adapter_checkpoint_dir=adapter_dir,
        use_4bit=use_4bit,
        max_new_tokens=max_new_tokens,
        temperature=temperature,
    )
    simulation_mode = not inference_model.load()

    # ── Metric accumulator ────────────────────────────────────────────────────
    calc = MetricCalculator()
    renderer = DashboardRenderer()
    all_sample_results: List[Dict[str, Any]] = []
    n_parse_fail = 0

    # ── Evaluation loop ───────────────────────────────────────────────────────
    logger.info(f"Beginning evaluation on {len(records)} samples ...")
    for idx, record in enumerate(records):
        instruction = record.get("instruction", "")
        user_input  = record.get("input", "")
        gt_output   = record.get("output", "")    # HIDDEN from model

        # Ground-truth parse (always from the JSONL 'output' field)
        gt = ForecastParser.parse_ground_truth(gt_output)

        # Generate prediction
        if simulation_mode:
            # In simulation mode, apply controlled Gaussian noise to GT values
            # to produce realistic but imperfect "predictions" for demo purposes.
            rng = np.random.RandomState(idx)
            noise_f = rng.normal(0, 15.0)
            noise_s = rng.normal(0, 2.5)
            pred = ParsedForecast(
                f15=gt.f15 + noise_f if gt.f15 else None,
                s15=gt.s15 + noise_s if gt.s15 else None,
                f30=gt.f30 + rng.normal(0, 18.0) if gt.f30 else None,
                s30=gt.s30 + rng.normal(0, 3.0)  if gt.s30 else None,
                f45=gt.f45 + rng.normal(0, 22.0) if gt.f45 else None,
                s45=gt.s45 + rng.normal(0, 3.5)  if gt.s45 else None,
                f60=gt.f60 + rng.normal(0, 25.0) if gt.f60 else None,
                s60=gt.s60 + rng.normal(0, 4.0)  if gt.s60 else None,
                rationale=gt_output.split("Rationale")[-1].strip()
                          if "Rationale" in gt_output else "",
                parse_success=True,
            )
            generated_text = gt_output    # Use GT as mock for display
        else:
            generated_text = inference_model.generate(instruction, user_input)
            pred = ForecastParser.parse(generated_text)

        if not pred.parse_success:
            n_parse_fail += 1

        # Accumulate errors
        calc.accumulate(gt, pred)

        # Demo display for first N samples
        if idx < demo_samples:
            renderer.render_sample(
                sample_idx=idx,
                record=record,
                gt=gt,
                pred=pred,
                generated_text=generated_text,
                simulation_mode=simulation_mode,
            )

        # Persist per-sample result
        all_sample_results.append({
            "idx": idx,
            "parse_success": pred.parse_success,
            "gt":   {"f15": gt.f15,   "s15": gt.s15,
                     "f30": gt.f30,   "s30": gt.s30,
                     "f45": gt.f45,   "s45": gt.s45,
                     "f60": gt.f60,   "s60": gt.s60},
            "pred": {"f15": pred.f15, "s15": pred.s15,
                     "f30": pred.f30, "s30": pred.s30,
                     "f45": pred.f45, "s45": pred.s45,
                     "f60": pred.f60, "s60": pred.s60},
        })

        if (idx + 1) % 50 == 0:
            logger.info(f"  Progress: {idx+1}/{len(records)} samples evaluated.")

    # ── Compute and display final metrics ─────────────────────────────────────
    horizon_metrics = calc.compute()
    renderer.render_metrics_table(horizon_metrics)

    parse_rate = 100.0 * (len(records) - n_parse_fail) / max(len(records), 1)
    mode_tag = "SIMULATION" if simulation_mode else "LIVE"
    print(f"\n  Mode            : {_c(mode_tag, YELLOW if simulation_mode else GREEN + BOLD)}")
    print(f"  Total samples   : {len(records)}")
    print(f"  Parse success   : {parse_rate:.1f}%  ({len(records)-n_parse_fail}/{len(records)})")
    print(f"  Parse failures  : {n_parse_fail}")
    print()

    # ── Save JSON report ──────────────────────────────────────────────────────
    report = {
        "mode": mode_tag,
        "model": model_name_or_path,
        "adapter_dir": adapter_dir,
        "n_samples": len(records),
        "n_parse_fail": n_parse_fail,
        "metrics": [
            {
                "horizon": m.horizon_label,
                "mae_flow":   round(m.mae_flow,   4) if not math.isnan(m.mae_flow)   else None,
                "rmse_flow":  round(m.rmse_flow,  4) if not math.isnan(m.rmse_flow)  else None,
                "mae_speed":  round(m.mae_speed,  4) if not math.isnan(m.mae_speed)  else None,
                "rmse_speed": round(m.rmse_speed, 4) if not math.isnan(m.rmse_speed) else None,
                "n_valid": m.n_valid,
            }
            for m in horizon_metrics
        ],
        "samples": all_sample_results,
    }

    os.makedirs(os.path.dirname(os.path.abspath(results_output)), exist_ok=True)
    with open(results_output, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)
    logger.info(f"Evaluation report saved → {results_output}")

    return report


